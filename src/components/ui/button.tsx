        xs: "h-(--ctl-xs) gap-1 rounded-sm px-2 text-xs leading-(--lh-small) in-data-[slot=button-group]:rounded-md has-data-[icon=inline-end]:pr-1 has-data-[icon=inline-start]:pl-1 [&_svg:not([class*='size-'])]:size-3",
